// Postgres persistence. In production this is Supabase Postgres (via `pg`); for local development and
// tests it is PGlite, an in-process Postgres, so the exact same SQL runs in both.
//
// Adapter interface:  { query(sql, params) -> {rows, rowCount}, connect() -> client, close() }
//   client:           { query, exec(sql), release() }     (exec runs multi-statement SQL)
// Schema changes go through MIGRATIONS (ordered, tracked in schema_migrations).
