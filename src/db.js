/* ---------------------------- adapters ---------------------------- */

/** Supabase / any Postgres. Use Supabase's "Transaction pooler" connection string on Vercel. */
export async function pgAdapter(connectionString) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(20, (v) => Number(v)); // int8 (COUNT etc.) as numbers
  const u = new URL(connectionString);
  const local = ['localhost', '127.0.0.1', '::1'].includes(u.hostname);
  u.searchParams.delete('sslmode'); // we set ssl explicitly below (Supabase's pooler cert chain isn't in Node's store)
  const pool = new pg.Pool({ connectionString: u.toString(), max: 4, idleTimeoutMillis: 60_000, ssl: local ? false : { rejectUnauthorized: false } });
  return {
    query: (sql, params) => pool.query(sql, params),
    async connect() {
      const c = await pool.connect();
      return { query: (s, p) => c.query(s, p), exec: (s) => c.query(s), release: () => c.release() };
    },
    close: () => pool.end(),
  };
}

/** In-process Postgres for local development and tests. `dir` = persist to that folder; omit for memory. */
export async function pgliteAdapter(dir) {
  const mod = '@electric-sql/pglite'; // dev/test only; kept non-literal so Vercel's bundler doesn't try to ship it
  const { PGlite } = await import(mod);
  if (dir) fs.mkdirSync(dir, { recursive: true });
  const pg = dir ? new PGlite(dir) : new PGlite();
  await pg.waitReady;
  let tail = Promise.resolve(); // PGlite is a single connection: serialise queries and transactions
  const acquire = async () => {
    const prev = tail;
    let release;
    tail = new Promise((r) => (release = r));
    await prev;
    return release;
  };
  const norm = (r) => ({ rows: r.rows, rowCount: r.affectedRows ?? r.rows.length });
  return {
    async query(sql, params) {
      const rel = await acquire();
      try {
        return norm(await pg.query(sql, params));
      } finally {
        rel();
      }
    },
    async connect() {
      const rel = await acquire();
      return { query: async (s, p) => norm(await pg.query(s, p)), exec: async (s) => (await pg.exec(s), { rows: [], rowCount: 0 }), release: rel };
    },
    close: () => pg.close(),
  };
}

/* ---------------------------- per-user seeding (templates -> the user's own rows) ---------------------------- */

export const BRANCHES = STREAMS.map((s) => ({ code: s.code, name: s.name }));

/** Give a user their own copy of the default root causes. `q(sql, params)` runs inside the caller's transaction. */
export async function seedCauses(q, uid) {
  const vals = [];
  const sql = CAUSES.map(([name, description, guidance], i) => (vals.push(uid, name, description, guidance, i), `($${vals.length - 4}, $${vals.length - 3}, $${vals.length - 2}, $${vals.length - 1}, $${vals.length})`)).join(',');
  await q(`INSERT INTO causes (user_id, name, description, guidance, sort) VALUES ${sql}`, vals);
}

/** Copy a branch template (e.g. "ME") into the user's account as their own stream, subjects and topics (3 queries, not hundreds). */
export async function seedBranch(q, uid, code) {
  const tpl = STREAMS.find((s) => s.code === code);
  if (!tpl) throw Object.assign(new Error(`Unknown branch "${code}"`), { status: 400 });
  const sort = (await q('SELECT COALESCE(MAX(sort), 0) + 1 AS n FROM streams WHERE user_id = $1', [uid])).rows[0].n;
  const streamId = (await q('INSERT INTO streams (user_id, code, name, sort) VALUES ($1, $2, $3, $4) RETURNING id', [uid, tpl.code, tpl.name, sort])).rows[0].id;
  const subjects = new Map(); // name -> { section, topics[] }
  for (const [section, name, topics] of tpl.syllabus) {
    if (!subjects.has(name)) subjects.set(name, { section, topics: [] });
    subjects.get(name).topics.push(...topics);
  }
  const sv = [];
  const ssql = [...subjects].map(([name, s], i) => (sv.push(uid, streamId, s.section, name, i), `($${sv.length - 4}, $${sv.length - 3}, $${sv.length - 2}, $${sv.length - 1}, $${sv.length})`)).join(',');
  const idByName = new Map((await q(`INSERT INTO subjects (user_id, stream_id, section, name, sort) VALUES ${ssql} RETURNING id, name`, sv)).rows.map((r) => [r.name, r.id]));
  const tv = [];
  const tsql = [];
  for (const [name, s] of subjects) {
    s.topics.forEach((t, j) => (tv.push(uid, idByName.get(name), t, j), tsql.push(`($${tv.length - 3}, $${tv.length - 2}, $${tv.length - 1}, $${tv.length})`)));
  }
  if (tsql.length) await q(`INSERT INTO topics (user_id, subject_id, name, sort) VALUES ${tsql.join(',')}`, tv);
  return streamId;
}

/* ---------------------------- migrate ---------------------------- */

export async function initDb(db) {
  // Fast path (every warm start and nearly every cold start): one query to see that the schema is already current.
  try {
    const v = (await db.query('SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations')).rows[0].v;
    if (v === MIGRATIONS.length && (await db.query("SELECT to_regclass('public.users') AS t")).rows[0].t) return;
  } catch {
    /* no schema_migrations table yet (brand-new database): fall through to the full migration below */
  }
  const c = await db.connect();
  try {
    await c.exec('BEGIN');
    await c.query('SELECT pg_advisory_xact_lock(7243001)'); // two cold starts must not migrate twice
    await c.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())');
    let v = (await c.query('SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations')).rows[0].v;
    if (v > MIGRATIONS.length) throw new Error(`Database schema v${v} is newer than this app (v${MIGRATIONS.length}). Deploy the latest version.`);
    if (v >= 1 && !(await c.query("SELECT to_regclass('public.users') AS t")).rows[0].t) {
      throw new Error('This database still has the old single-user tables. In Supabase → SQL Editor run: drop table if exists schema_migrations, attachments, topic_progress, study_log, tasks, reviews, mistakes, tests, causes, topics, subjects, streams, settings, users cascade;  — then redeploy.');
    }
    for (; v < MIGRATIONS.length; v++) {
      await c.exec(MIGRATIONS[v]);
      await c.query('INSERT INTO schema_migrations (version) VALUES ($1)', [v + 1]);
    }
    await c.exec('COMMIT');
  } catch (e) {
    await c.exec('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    c.release();
  }
}
